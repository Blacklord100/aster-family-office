export const timelineEvents: TimelineEvent[] = eventSeeds.map(
  ([
    id,
    holdingId,
    type,
    title,
    summary,
    date,
    status,
    materiality,
    amountEUR,
  ]) => {
    const holding = holdings.find((item) => item.id === holdingId)!;
    const eventSourceId = `source-${id}`;
    evidenceSources.push({
      id: eventSourceId,
      mailboxId: mailboxFor[holding.familyId],
      familyId: holding.familyId,
      holdingId,
      subject: title,
      sender: `${type === 'Public news' ? 'Aster public briefing' : holding.manager} <updates@reports.example>`,
      receivedAt: `${date}T08:15:00Z`,
      effectiveDate: date,
      filename: `${id}_synthetic_${type === 'Public news' ? 'article' : 'email'}.txt`,
      page: 1,
      excerpt: `SYNTHETIC DEMONSTRATION. ${title}. ${summary}`,
      status: status === 'Needs review' ? 'Needs review' : 'Accepted',
      synthetic: true,
    });
    return {
      id,
      familyId: holding.familyId,
      holdingIds: [holdingId],
      entityId: holding.entityId,
      type,
      title,
      summary,
      date,
      receivedAt: `${date}T08:15:00Z`,
      sourceId: eventSourceId,
      status,
      materiality,
      amountEUR,
      financialEffect:
        type === 'Valuation' && status === 'Accepted'
          ? 'Accepted valuation'
          : 'None',
    };
  },
);

